@triton.jit
def _decodificar_e4m3(bits):
    """Bits de FP8 E4M3 (leídos como int8) -> valor fp32. Sin FP8 nativo."""
    b = bits.to(tl.int32) & 0xFF
    signo = tl.where(b >= 128, -1.0, 1.0)
    exp = (b >> 3) & 0x0F
    m_int = (b & 0x07) + tl.where(exp != 0, 8, 0)
    return signo * m_int.to(tl.float32) * tl.exp2((tl.maximum(exp, 1) - 10).to(tl.float32))


@triton.jit
def _amax_por_bloque_kernel(
    w_ptr, s_inv_ptr, out_ptr,
    stride_wn, stride_sn, stride_sk, stride_on,
    BN_BLK: tl.constexpr, BK: tl.constexpr,
):
    """amax de |peso real| por (fila n, bloque de K) -> ``out`` [N, Kb] fp32."""
    n = tl.program_id(0)
    kb = tl.program_id(1)
    offs = tl.arange(0, BK)
    v = _decodificar_e4m3(tl.load(w_ptr + n * stride_wn + kb * BK + offs))
    s = tl.load(s_inv_ptr + (n // BN_BLK) * stride_sn + kb * stride_sk)
    tl.store(out_ptr + n * stride_on + kb, tl.max(tl.abs(v)) * s)


@triton.jit
def _quant_inplace_triton(
    w_ptr, q_ptr, s_inv_ptr, s_row_ptr, shift_ptr,
    stride_wn, stride_sn, stride_sk, stride_shn, stride_shk,
    BN_BLK: tl.constexpr, BK: tl.constexpr,
):
    """Escribe el INT8 **sobre los mismos bytes** que ocupaba el FP8.

    Cada programa toca ``[n, kb*BK : (kb+1)*BK]``, rangos disjuntos entre
    programas, y lee antes de escribir dentro del programa: in-place seguro.
    """
    n = tl.program_id(0)
    kb = tl.program_id(1)
    offs = tl.arange(0, BK)
    base = n * stride_wn + kb * BK + offs
    v = _decodificar_e4m3(tl.load(w_ptr + base))
    s = tl.load(s_inv_ptr + (n // BN_BLK) * stride_sn + kb * stride_sk)
    paso = tl.load(s_row_ptr + n) * tl.exp2(
        tl.load(shift_ptr + (n // BN_BLK) * stride_shn + kb * stride_shk).to(tl.float32))
    x = v * s / paso
    q = (x + tl.where(x >= 0.0, 0.5, -0.5)).to(tl.int32)
    tl.store(q_ptr + base, tl.minimum(tl.maximum(q, -127), 127).to(tl.int8))


