_quant_inplace_kernel = _quant_inplace_triton


def requantizar_fp8_a_int8_inplace(
    w_fp8: torch.Tensor,
    scale_inv: torch.Tensor,
    block_size: tuple[int, int] = (128, 128),
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """FP8 [N,K] -> INT8 diádico in-place.

    :param w_fp8: peso [N,K] ``float8_e4m3fn`` contiguo. **Se sobrescribe.**
    :param scale_inv: escalas por bloque [N/Bn, K/Bk] fp32.
    :param block_size: (Bk, Bn).
    :returns: ``(b_col, w_scales, w_shifts)`` donde ``b_col`` es una **vista**
        int8 [K,N] column-major del mismo storage que ``w_fp8``, ``w_scales`` es
        [N,1] fp32 y ``w_shifts`` es [Kb, Nb] int8 con el layout que esperan los
        super kernels.
    """
    bk, bn = block_size
    n, k = w_fp8.shape
    kb_n, nb_n = k // bk, n // bn
    dev = w_fp8.device
    bits = w_fp8.view(torch.int8)

    # Pasada 1 — sólo lee. amax del peso real por (fila, bloque de K).
    amax_nk = torch.empty((n, kb_n), dtype=torch.float32, device=dev)
    _amax_por_bloque_kernel[(n, kb_n)](
        bits, scale_inv, amax_nk,
        bits.stride(0), scale_inv.stride(0), scale_inv.stride(1), amax_nk.stride(0),
        BN_BLK=bn, BK=bk, num_warps=4, num_stages=1,
    )

    # Escala por canal de salida y shift diádico por bloque. Todo sobre
    # tensores [N, Kb] = 2.8 MB, no sobre el peso.
    s_row = (amax_nk.amax(dim=1) / 127.0).clamp(min=1e-30)              # [N]
    need = torch.log2((amax_nk / (127.0 * s_row[:, None])).clamp(min=1e-30))
    shift = torch.ceil(need.reshape(nb_n, bn, kb_n).amax(dim=1)).clamp(-10.0, 10.0)

    # Pasada 2 — escribe INT8 encima del FP8.
    if (_ptx_habilitado() and bk == 128 and bn == 128
            and scale_inv.stride(1) == 1 and shift.stride(1) == 1):
        # Camino nativo: args en EXACTO orden de declaracion (constexpr
        # inline). El cubin lleva horneados stride_sk=1, stride_shk=1,
        # BN_BLK=128 y BK=128 (guardados arriba). Grid (n, kb_n), 4 warps.
        _PTQ_KERNEL((n, kb_n), bits, bits, scale_inv, s_row, shift,
                    bits.stride(0), scale_inv.stride(0), scale_inv.stride(1),
                    shift.stride(0), shift.stride(1), bn, bk)
    else:
        _quant_inplace_triton[(n, kb_n)](
            bits, bits, scale_inv, s_row, shift,
            bits.stride(0), scale_inv.stride(0), scale_inv.stride(1),
            shift.stride(0), shift.stride(1),
            BN_BLK=bn, BK=bk, num_warps=4, num_stages=1,
        )

    # b_col: misma memoria, sólo strides. [K,N] con stride (1,K).
    return bits.t(), s_row.unsqueeze(1).contiguous(), shift.t().contiguous().to(torch.int8)


