"""requant_inplace — FP8 E4M3 -> INT8 diádico **sobre el mismo buffer**.

Por qué existe
--------------
La conversión anterior materializaba **cuatro copias completas** del peso por
capa, todas vivas a la vez:

  1. ``w_fp8_orig`` [N,K] original
  2. ``w_fp8_orig.t().contiguous()`` — transpuesta fp8
  3. ``w_int8`` [K,N] que sale del requantizador
  4. ``b_col.copy_(w_int8)`` — otra vez, a column-major

Y ``process_weights_after_loading`` corre dentro del pool ``weights`` del
asignador cumem, donde **lo liberado no se devuelve** hasta salir del contexto.
Con 12.17 GB de pesos por rank quedaban retenidos ~24 GB sobre los 23.56 de una
3090, y el arranque moría con ``CUDA Error: out of memory at
cumem_allocator.cpp:163``.

La observación que elimina las cuatro copias:

    empty_strided((K, N), (1, K))  ==  [N, K] contiguo, transpuesto

Son los mismos bytes en el mismo orden, y ``w_fp8_orig`` **ya** es [N,K]
contiguo. Como FP8 e INT8 miden 1 byte, ``w.view(torch.int8).t()`` es
exactamente el ``b_col`` [K,N] column-major que esperan los super kernels,
compartiendo storage. Y como la cuantización es elementwise (tras una pasada de
amax que sólo lee), el INT8 se escribe **encima** del FP8.

Resultado: 4x -> 1x. El peso original y el nuevo son el mismo tensor.

Decodificación de E4M3 sin FP8 nativo
-------------------------------------
sm_86 **no** tiene FP8 en Triton::

    ValueError: type fp8e4nv not supported in this architecture.
                The supported fp8 dtypes are ('fp8e4b15', 'fp8e5')

Así que el byte se lee como entero y se decodifica a mano::

    signo    = bits & 0x80
    exp      = (bits >> 3) & 0x0F
    mantisa  = bits & 0x07
    m_int    = mantisa + (8 si exp != 0 else 0)     # el 1 implícito
    valor    = ±m_int * 2^(max(exp, 1) - 10)

``max(exp,1)-10`` cubre normales y subnormales con la misma expresión: para
exp=0 y exp=1 el exponente es -9, que es la propiedad estándar de los
subnormales. Todo entero salvo el ``exp2`` final.

Los kernels no validan nada: se asume comprobado aguas arriba.
"""

